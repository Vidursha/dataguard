"""Creates the applications, subscriptions and OAuth2 keys (Developer Portal REST API v3)."""

from __future__ import annotations

from common import (
    AI_AGENT_APP, AI_AGENT_OWNER, AI_AGENT_POLICY, DEVPORTAL_SCOPES, API_CONTEXT, API_VERSION, DASHBOARD_APP, DASHBOARD_POLICY, DEVPORTAL,
    FRONTEND_ORIGIN, GATEWAY_URL, MGMT_URL, ROOT, Client, env, find_one, info, step, update_env, user_client,
)

KEY_MANAGER = "Resident Key Manager"

# After sign-in WSO2 sends the user back to /callback, and after sign-out to /.
DASHBOARD_CALLBACK = f"regexp=({FRONTEND_ORIGIN}/callback|{FRONTEND_ORIGIN}/)"

APPS = {
    DASHBOARD_APP: {
        "policy": DASHBOARD_POLICY,
        "description": "DataGuard web dashboard (browser SPA, OAuth2 Authorization Code + PKCE)",
        "grants": ["authorization_code"],  # no refresh tokens in the browser, people just sign in again when the token expires
        "callback": DASHBOARD_CALLBACK,
        # Public client: PKCE (S256) is required and there's no client secret,
        # because a browser can't keep a secret.
        "properties": {"pkceMandatory": "true", "pkceSupportPlain": "false", "bypassClientCredentials": "true"},
    },
    AI_AGENT_APP: {
        "policy": AI_AGENT_POLICY,
        "description": "AI assistants using the DataGuard MCP server (OAuth2 client credentials, "
                       "owned by the ai-agent-svc account so tokens only carry analyst rights)",
        "grants": ["client_credentials"],
        "callback": "",
        "properties": {},
    },
}


def ensure_app(client: Client, name: str, config: dict) -> str:
    apps = client.get(f"{DEVPORTAL}/applications", params={"query": name, "limit": 100})["list"]
    body = {"name": name, "throttlingPolicy": config["policy"], "description": config["description"],
            "tokenType": "JWT"}
    existing = find_one(apps, name=name)
    if existing:
        client.put(f"{DEVPORTAL}/applications/{existing['applicationId']}", json=body)
        info(f"application '{name}' exists; policy {config['policy']} ensured")
        return existing["applicationId"]
    created = client.post(f"{DEVPORTAL}/applications", json=body)
    info(f"application '{name}' created with policy {config['policy']}")
    return created["applicationId"]


def ensure_keys(client: Client, app_id: str, name: str, config: dict) -> dict:
    keys = client.get(f"{DEVPORTAL}/applications/{app_id}/oauth-keys")["list"]
    current = find_one(keys, keyType="PRODUCTION", keyManager=KEY_MANAGER)
    if current:
        properties = {**(current.get("additionalProperties") or {}), **config["properties"]}
        body = {**current, "supportedGrantTypes": config["grants"], "callbackUrl": config["callback"],
                "additionalProperties": properties}
        result = client.put(f"{DEVPORTAL}/applications/{app_id}/oauth-keys/{current['keyMappingId']}", json=body)
        info(f"'{name}' production keys updated: {', '.join(config['grants'])}")
    else:
        result = client.post(f"{DEVPORTAL}/applications/{app_id}/generate-keys", json={
            "keyType": "PRODUCTION", "keyManager": KEY_MANAGER, "grantTypesToBeSupported": config["grants"],
            "callbackUrl": config["callback"], "additionalProperties": config["properties"],
        })
        info(f"'{name}' production keys generated: {', '.join(config['grants'])}")
    return result


def ensure_subscription(client: Client, app_id: str, app_name: str, api_id: str, label: str) -> None:
    subs = client.get(f"{DEVPORTAL}/subscriptions", params={"applicationId": app_id, "limit": 100})["list"]
    if find_one(subs, apiId=api_id):
        info(f"'{app_name}' already subscribed to {label}")
        return
    client.post(f"{DEVPORTAL}/subscriptions",
                json={"applicationId": app_id, "apiId": api_id, "throttlingPolicy": "Unlimited"})
    info(f"'{app_name}' subscribed to {label}")


def write_frontend_env(client_id: str) -> None:
    """The dashboard's client ID isn't secret (it's a PKCE public client), but the
    file is still git-ignored because it's different on every machine.
    """
    path = ROOT / "frontend" / ".env.local"
    path.parent.mkdir(exist_ok=True)
    path.write_text(
        "# Generated by wso2/scripts/setup_all.py. Do not commit.\n"
        f"VITE_WSO2_CLIENT_ID={client_id}\n"
        f"VITE_WSO2_URL={MGMT_URL}\n"
        f"VITE_GATEWAY_API_URL={GATEWAY_URL}{API_CONTEXT}/{API_VERSION}\n",
        encoding="utf-8",
    )
    info(f"wrote {path.relative_to(ROOT)}")


def agent_client() -> Client:
    """Developer Portal client that acts as the AI agent's service account (it owns the AI Agent app)."""
    return user_client(AI_AGENT_OWNER, env()["AI_AGENT_SERVICE_PASSWORD"], DEVPORTAL_SCOPES)


def run(admin: Client, api_id: str) -> dict[str, str]:
    step("Applications, subscriptions and keys")
    clients = {DASHBOARD_APP: admin, AI_AGENT_APP: agent_client()}
    app_ids: dict[str, str] = {}
    for name, config in APPS.items():
        client = clients[name]
        app_id = ensure_app(client, name, config)
        app_ids[name] = app_id
        ensure_subscription(client, app_id, name, api_id, "DataGuard Sales API")
        keys = ensure_keys(client, app_id, name, config)
        if name == DASHBOARD_APP:
            write_frontend_env(keys["consumerKey"])
        else:
            update_env({"AI_AGENT_CLIENT_ID": keys["consumerKey"], "AI_AGENT_CLIENT_SECRET": keys["consumerSecret"]})
            info("AI Agent client credentials saved to .env")
    return app_ids
